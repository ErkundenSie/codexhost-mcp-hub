export function createTranslator(locale) {
  const dict = String(locale ?? "").toLowerCase().startsWith("zh")
    ? MESSAGES["zh-CN"]
    : MESSAGES.en;
  return (key, vars) => {
    let text = dict[key] ?? MESSAGES.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replaceAll(`{${k}}`, String(v));
      }
    }
    return text;
  };
}
